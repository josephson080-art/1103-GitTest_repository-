"""
Practice 1 
How can we swap the values of two variables?
• first = 10, second = 20
• first = 20, second = 10
"""
#Variables 
first = str(10) 
second = str(20)
VariableStorage = str(0) 
#Solution
VariableStorage = first
first = second 
second = VariableStorage
#Checking answer practice 1 
print("Practice 1 : \n first = " + first + " \n second = " + second)

